-- migrations/0004_analysis_proposals.sql
--
-- Step 9 — Phase 5/6 reflection diff proposals.
--
-- Each reflection pass emits 0..N proposals (concept §4-Phase 5).
-- The operator reviews them in the SPA Reflect tab; accepted
-- proposals go through ApplyProposal (Phase 6) which writes the
-- diff into analysis_nodes append-only style + creates a :Learning
-- node tying the change back to the simulation run that produced it.
--
-- See concepts/organizational_memory_and_learning.md §4-Phase 5/6
-- and §13 row 9.

BEGIN;

CREATE TABLE IF NOT EXISTS analysis_proposals (
    id                       UUID        PRIMARY KEY,
    analysis_id              UUID        NOT NULL REFERENCES analyses(id) ON DELETE CASCADE,
    -- The operator who *emitted* the reflection (not necessarily the
    -- one who later approves; we record both — see decided_by).
    -- Multi-tenant filter joins on analyses.operator_id; this column
    -- is here for fast-path audit only.
    operator_id              TEXT        NOT NULL REFERENCES users(id),

    -- Operator-supplied simulation handle. NOT a foreign key — there
    -- is no simulation_runs table in v1 (Step 8 Q1=(a) deferred a
    -- transcript store). Free-form so the operator can paste anything
    -- meaningful (a session uuid, a wall-clock label, etc.).
    simulation_run_id        TEXT,

    -- One reflection pass = many proposals. Grouped by reflection_run_id
    -- so the SPA can render "5 proposals from your 14:32 reflection pass".
    -- UUID generated by the gateway when it persists the agent response.
    reflection_run_id        UUID        NOT NULL,

    -- 'A' = single-loop (additive correction), 'B' = double-loop
    -- (governing belief contradicted). Mirrors agents/reflection/schema.py.
    kind                     CHAR(1)     NOT NULL CHECK (kind IN ('A','B')),

    -- One of add_node | edit_node | deprecate_node. Reflection v1 does
    -- not propose edge mutations directly (those follow from node
    -- additions / supersessions).
    operation                TEXT        NOT NULL
                              CHECK (operation IN ('add_node','edit_node','deprecate_node')),

    -- Walsh-Ungson bin label this proposal targets (Friction, Belief, ...).
    target_label             TEXT        NOT NULL,

    -- For edit_node / deprecate_node: the live node the diff applies to.
    -- For add_node: NULL (Phase 6 creates a fresh node).
    target_node_id           UUID        REFERENCES analysis_nodes(id),

    -- For add_node: full payload of the new node. For edit_node: sparse
    -- field-overwrite map. For deprecate_node: {}.
    payload_diff             JSONB       NOT NULL DEFAULT '{}'::jsonb,

    -- Why this matters, in the agent's words. Surfaced to the operator.
    rationale                TEXT        NOT NULL,

    -- Array of {moment_id, quote, transcript_index}. LOCKED §12.4: every
    -- Type-B proposal has at least one citation; Type-A proposals MAY have
    -- citations but are not rejected for missing them.
    transcript_citations     JSONB       NOT NULL DEFAULT '[]'::jsonb,

    -- Informational flag: agent's hint that approving this proposal
    -- contradicts an operator-marked governing belief. The SPA shows
    -- a stronger confirmation modal in that case (LOCKED §12.2: only
    -- the operator may revise governing status).
    touches_governing_belief BOOLEAN     NOT NULL DEFAULT FALSE,

    -- The operator's "what surprised you" annotation that produced this
    -- reflection pass. Stored on each proposal row (denormalised) so
    -- the SPA queue card shows the trigger context without a join.
    operator_annotation      TEXT,

    -- 'pending' on insert. → 'accepted' (Phase 6 applied) | 'rejected'
    -- (operator declined) | 'superseded' (a later proposal took over).
    -- 'superseded' is reserved for v2 — v1 only writes pending/accepted/rejected.
    status                   TEXT        NOT NULL DEFAULT 'pending'
                              CHECK (status IN ('pending','accepted','rejected','superseded')),

    -- Set when status leaves 'pending'.
    decided_at               TIMESTAMPTZ,
    decided_by               TEXT        REFERENCES users(id),

    -- For status='accepted': the :Learning node row this proposal
    -- created (Phase 6 institutionalization). NULL otherwise.
    applied_learning_node_id UUID        REFERENCES analysis_nodes(id),
    -- For status='accepted' on add_node / edit_node: the new node row
    -- the proposal wrote (separate from the Learning node so the SPA
    -- can deep-link). NULL for deprecate_node (no new node row).
    applied_node_id          UUID        REFERENCES analysis_nodes(id),

    created_at               TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Hot path A: SPA Reflect tab fetching pending proposals for an analysis.
CREATE INDEX IF NOT EXISTS analysis_proposals_pending_idx
    ON analysis_proposals(analysis_id, created_at DESC)
    WHERE status = 'pending';

-- Hot path B: filter by reflection_run_id so the SPA can collapse
-- "all proposals from this run" in the queue.
CREATE INDEX IF NOT EXISTS analysis_proposals_run_idx
    ON analysis_proposals(analysis_id, reflection_run_id);

-- Hot path C: filter by target node so accepting one diff that affects
-- the same target as a pending second proposal can auto-supersede it
-- (v2 — not used in v1).
CREATE INDEX IF NOT EXISTS analysis_proposals_target_idx
    ON analysis_proposals(analysis_id, target_node_id)
    WHERE target_node_id IS NOT NULL;

COMMIT;
