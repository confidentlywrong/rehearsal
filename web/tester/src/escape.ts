/**
 * Lightweight HTML entity escaping for untrusted text interpolated into
 * innerHTML templates.  Use this instead of DOMPurify when the value
 * should never contain HTML (session IDs, agent types, log messages).
 */

const ESCAPE_MAP: Record<string, string> = {
  "&": "&amp;",
  "<": "&lt;",
  ">": "&gt;",
  '"': "&quot;",
  "'": "&#39;",
};

export function escapeHTML(str: unknown): string {
  return String(str ?? "").replace(/[&<>"']/g, (c) => ESCAPE_MAP[c]);
}
